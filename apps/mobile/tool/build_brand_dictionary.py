"""Rebuild the coordinate-free NSI subset from a fixed upstream revision."""
import json
import pathlib
import re
import urllib.request

COMMIT = "fd4f3c84636838ac2f514a3f00e6a5eb415d59ae"
BASE = f"https://raw.githubusercontent.com/osmlab/name-suggestion-index/{COMMIT}/"
MOBILE = pathlib.Path(__file__).resolve().parents[1]
PATHS = {
    "amenity/fast_food": "catering.fast_food",
    "amenity/restaurant": "catering.restaurant",
    "amenity/cafe": "catering.cafe",
    "amenity/pharmacy": "healthcare.pharmacy",
    "amenity/bank": "service.financial.bank",
    "amenity/fuel": "service.vehicle.fuel",
    "shop/convenience": "commercial.convenience",
    "shop/supermarket": "commercial.supermarket",
    "shop/department_store": "commercial.department_store",
    "shop/mall": "commercial.shopping_mall",
    "shop/bakery": "commercial.food_and_drink.bakery",
}


def fetch(path):
    request = urllib.request.Request(BASE + path, headers={"User-Agent": "Wayday-dictionary-build"})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read().decode("utf-8")


def eligible(scope):
    include, exclude = scope.get("include", []), scope.get("exclude", [])
    if any(not isinstance(code, str) or not re.fullmatch(r"[a-z]{2}|001", code) for code in include + exclude):
        return None
    return ("ph" in include or "001" in include) and "ph" not in exclude


def main():
    brands, counts = {}, {"unsupported_geography": 0, "outside_philippines": 0}
    for path, category in PATHS.items():
        # NSI's JSON sources permit comments/trailing commas. Protect quoted
        # strings (including URLs) while removing only that JSON5 syntax.
        source = fetch(f"data/brands/{path}.json")
        source = re.sub(r'("(?:\\.|[^"\\])*")|//[^\n]*|/\*[\s\S]*?\*/|,\s*(?=[}\]])', lambda m: m.group(1) or "", source)
        payload = json.loads(source)
        for item in payload["items"]:
            allowed = eligible(item.get("locationSet", {}))
            if allowed is not True:
                counts["unsupported_geography" if allowed is None else "outside_philippines"] += 1
                continue
            tags = item.get("tags", {})
            name = tags.get("brand") or tags.get("name")
            if not name or len(name) > 100:
                continue
            record = brands.setdefault(name, {"name": name, "aliases": set(), "categories": set()})
            for alias in [name, tags.get("name"), tags.get("name:en"), tags.get("brand:en"), *item.get("matchNames", [])]:
                if alias and len(alias) <= 100 and not re.search(r"[\[\]{}\\^$|*+?]", alias):
                    record["aliases"].add(alias)
            record["categories"].add(category)
    # Reviewed local shorthand; these are brand terms, never branch locations.
    for name, aliases in {"McDonald's": ["McDo", "mc donalds"], "Jollibee": ["Jolibee"]}.items():
        brands.setdefault(name, {"name": name, "aliases": set(), "categories": {"catering.fast_food"}})["aliases"].update(aliases)
    records = [{"name": b["name"], "aliases": sorted(b["aliases"]), "categories": sorted(b["categories"])} for b in sorted(brands.values(), key=lambda b: b["name"].casefold())]
    data = json.dumps(records, ensure_ascii=False, separators=(",", ":"))
    assert "'''" not in data
    output = MOBILE / "lib/features/places/domain/philippine_brands.g.dart"
    output.write_text(f"// Generated by tool/build_brand_dictionary.py. Do not edit.\n// NSI 8.0.20260918, {COMMIT}; BSD-3-Clause.\nconst philippineBrandsJson = r'''{data}''';\n", encoding="utf-8")
    notices = MOBILE / "assets/notices/nsi"
    notices.mkdir(parents=True, exist_ok=True)
    (notices / "LICENSE.txt").write_text(fetch("LICENSE.md"), encoding="utf-8")
    manifest = {"version": "8.0.20260918", "commit": COMMIT, "license": "BSD-3-Clause", "brands": len(records), "source_paths": list(PATHS), "omissions": counts, "scope": "Explicit PH/global country rules only; no logos, coordinates, or complex geography."}
    (notices / "SOURCE.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
