"""Compile a minimal PH validation mask; never retain the raw world dataset."""
import hashlib
import json
import pathlib
import urllib.request

COMMIT = "f1890d9f152c896d250a77557a5751a93d494776"
URL = f"https://raw.githubusercontent.com/nvkelso/natural-earth-vector/{COMMIT}/geojson/ne_10m_admin_0_countries.geojson"
MOBILE = pathlib.Path(__file__).resolve().parents[1]

def main():
    request = urllib.request.Request(URL, headers={"User-Agent": "Wayday-country-mask-build"})
    with urllib.request.urlopen(request, timeout=90) as response:
        raw = response.read()
    features = json.loads(raw)["features"]
    country = [f for f in features if f["properties"].get("ADM0_A3") == "PHL"]
    assert len(country) == 1
    geometry = country[0]["geometry"]
    assert geometry["type"] == "MultiPolygon"
    # Preserve all rings/holes and source precision. No branch or Google data.
    coordinates = geometry["coordinates"]
    compact = json.dumps(coordinates, separators=(",", ":"))
    output = MOBILE / "lib/features/places/domain/philippine_boundary.g.dart"
    output.write_text(f"// Generated by tool/build_philippine_boundary.py.\n// Natural Earth v5.1.2, {COMMIT}; public domain.\nconst philippineBoundaryJson = r'''{compact}''';\n", encoding="utf-8")
    notices = MOBILE / "assets/notices/natural-earth"
    notices.mkdir(parents=True, exist_ok=True)
    manifest = {"source": URL, "release": "v5.1.2", "commit": COMMIT,
        "source_sha256": hashlib.sha256(raw).hexdigest(), "license": "public domain",
        "feature": "PHL", "polygons": len(coordinates),
        "vertices": sum(len(ring) for polygon in coordinates for ring in polygon),
        "generated_bytes": output.stat().st_size,
        "limitations": "Cartographic land mask, not legal/marine boundaries. Islands, coastal reclamation and shoreline precision may be incomplete. Unconfirmed points fail closed."}
    (notices / "SOURCE.json").write_text(json.dumps(manifest, indent=2)+"\n", encoding="utf-8")
    (notices / "NOTICE.txt").write_text("Made with Natural Earth. Public-domain cartographic country data.\nhttps://www.naturalearthdata.com/about/terms-of-use/\nPHL subset from Natural Earth Vector v5.1.2. This validation mask is not a legal boundary or navigation/access guarantee. Raw world data is not bundled.\n", encoding="utf-8")
    print(json.dumps({key: manifest[key] for key in ["polygons", "vertices", "generated_bytes", "source_sha256"]}))

if __name__ == "__main__":
    main()
